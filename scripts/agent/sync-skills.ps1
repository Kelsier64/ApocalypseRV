# Regenerates the thin Claude Code skill entry points in .claude/skills from the
# shared sources in .agents/skills. -Check reports drift without writing.
[CmdletBinding()]
param([switch]$Check)
$ErrorActionPreference = 'Stop'
$root = Split-Path (Split-Path $PSScriptRoot -Parent) -Parent
$sourceRoot = Join-Path $root '.agents/skills'
$targetRoot = Join-Path $root '.claude/skills'
$marker = '<!-- Generated by scripts/agent/sync-skills.ps1. Edit the source skill, then rerun the script. -->'
$utf8 = [Text.UTF8Encoding]::new($false)
$drift = [Collections.Generic.List[string]]::new()

$expected = @{}
foreach ($source in Get-ChildItem -LiteralPath $sourceRoot -Directory) {
    $file = Join-Path $source.FullName 'SKILL.md'
    if (-not (Test-Path -LiteralPath $file)) { continue }
    $text = [IO.File]::ReadAllText($file, $utf8)
    $frontmatter = [regex]::Match($text, '\A---\r?\n(.*?)\r?\n---', 'Singleline')
    $name = [regex]::Match($frontmatter.Groups[1].Value, '(?m)^name:\s*(.+?)\s*$').Groups[1].Value
    $description = [regex]::Match($frontmatter.Groups[1].Value, '(?m)^description:\s*(.+?)\s*$').Groups[1].Value
    if (-not $name -or -not $description) { throw "Missing name or description in $file" }
    if ($name -ne $source.Name) { throw "Skill name '$name' must match its folder '$($source.Name)'" }
    $expected[$name] = @(
        '---', "name: $name", "description: $description", '---', '', $marker, '',
        "Read [the shared skill](../../../.agents/skills/$name/SKILL.md) and follow it. Resolve its relative links and run its scripts from ``.agents/skills/$name/``.", ''
    ) -join "`n"
}

foreach ($name in $expected.Keys) {
    $target = Join-Path $targetRoot "$name/SKILL.md"
    $current = if (Test-Path -LiteralPath $target) { [IO.File]::ReadAllText($target, $utf8) } else { $null }
    if ($current -ceq $expected[$name]) { continue }
    $drift.Add($name)
    if (-not $Check) {
        New-Item -ItemType Directory -Force -Path (Split-Path $target) | Out-Null
        [IO.File]::WriteAllText($target, $expected[$name], $utf8)
    }
}
foreach ($stale in Get-ChildItem -LiteralPath $targetRoot -Directory -ErrorAction SilentlyContinue) {
    if ($expected.ContainsKey($stale.Name)) { continue }
    $file = Join-Path $stale.FullName 'SKILL.md'
    if (-not (Test-Path -LiteralPath $file) -or -not ([IO.File]::ReadAllText($file, $utf8)).Contains($marker)) { continue }
    $drift.Add("$($stale.Name) (stale)")
    if (-not $Check) { Remove-Item -LiteralPath $stale.FullName -Recurse -Force }
}

if ($drift.Count -eq 0) { Write-Output 'Skill entry points are in sync.'; exit 0 }
if ($Check) { Write-Output "Out of sync: $($drift -join ', ')"; exit 1 }
Write-Output "Updated: $($drift -join ', ')"
